import 'app_language.dart';

/// Idioma activo de la app y acceso a los textos traducidos.
///
/// Es un holder estático (mismo patrón que `AppColors`): se fija con
/// [setLanguage] desde el `localeProvider` y se lee desde cualquier sitio,
/// también fuera de widgets (providers, servicios, formatters). Los widgets
/// `const` no se reconstruyen solos al cambiar el idioma, así que el árbol se
/// re-teclea por idioma en `AppShell` (igual que con el tema).
class S {
  S._();

  static AppLanguage _lang = AppLanguage.en;

  static AppLanguage get lang => _lang;

  static void setLanguage(AppLanguage lang) => _lang = lang;

  static bool get isRtl => _lang.isRtl;
}

/// Texto traducido al idioma activo. Sustituye `{clave}` por el valor de [args].
///
/// Si falta la clave o el idioma, cae a inglés, luego a español y por último a
/// la propia clave (para no romper la UI si algo se quedó sin traducir).
String tr(String key, [Map<String, Object?>? args]) {
  final entry = _translations[key];
  String template;
  if (entry == null) {
    assert(false, 'Falta la clave de traducción: $key');
    template = key;
  } else {
    template = entry[S.lang] ??
        entry[AppLanguage.en] ??
        entry[AppLanguage.es] ??
        key;
  }
  if (args != null && args.isNotEmpty) {
    args.forEach((k, v) {
      template = template.replaceAll('{$k}', '${v ?? ''}');
    });
  }
  return template;
}

/// Variante con plural. Usa las claves `$key.one` / `$key.other` y elige según
/// el número [n] (que además queda disponible como `{n}`). Los idiomas sin
/// flexión de plural (ja, ko, zh) usan siempre la forma `other`.
String trn(String key, int n, [Map<String, Object?>? args]) {
  final category = switch (S.lang) {
    AppLanguage.ja || AppLanguage.ko || AppLanguage.zh => 'other',
    _ => n == 1 ? 'one' : 'other',
  };
  return tr('$key.$category', {'n': n, ...?args});
}

